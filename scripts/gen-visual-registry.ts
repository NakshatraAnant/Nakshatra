/**
 * Generates src/web/lib/visual-registry.generated.ts from the Ink & Ember asset
 * manifest (docs/visual-system/asset-manifest.json) and verifies that every file
 * the manifest names exists under public/visual/. Run: npx tsx scripts/gen-visual-registry.ts
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

interface Entry { id: string; file: string; format: string; category: string; width?: number; height?: number; decorative?: boolean; alt?: string; crop?: string }

const root = resolve(import.meta.dirname, '..');
const manifest = JSON.parse(readFileSync(resolve(root, 'docs/visual-system/asset-manifest.json'), 'utf8')) as Entry[] | { assets: Entry[] };
const entries = Array.isArray(manifest) ? manifest : manifest.assets;

const missing: string[] = [];
const out: Record<string, [string, number, number, string, string]> = {};
for (const e of entries) {
  if (!['svg', 'png'].includes(e.format)) continue;
  if (!existsSync(resolve(root, 'public/visual', e.file))) { missing.push(e.file); continue; }
  // Object-position from the crop note, when it names one ("object-position 72% 50%").
  const pos = /(\d{1,3}%\s+\d{1,3}%)/.exec(e.crop ?? '')?.[1] ?? '';
  out[e.id] = [`/visual/${e.file}`, e.width ?? 0, e.height ?? 0, e.decorative ? '' : (e.alt ?? ''), pos];
}
if (missing.length) {
  console.error(`Missing ${missing.length} manifest files:\n${missing.join('\n')}`);
  process.exit(1);
}
const body = `// Generated by scripts/gen-visual-registry.ts from docs/visual-system/asset-manifest.json. Do not edit.
// [path, width, height, alt ('' = decorative), object-position]
export const VISUAL_REGISTRY: Record<string, readonly [string, number, number, string, string]> = ${JSON.stringify(out)};
`;
writeFileSync(resolve(root, 'src/web/lib/visual-registry.generated.ts'), body);
console.log(`Wrote ${Object.keys(out).length} assets (of ${entries.length} manifest entries).`);
